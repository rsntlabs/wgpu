#!/usr/bin/env python3
"""Regenerate fused binary32 RZ/RN references from exact bigint units 2^-298."""
from pathlib import Path
import random

MASK = 0x7fffffff
INF = 0x7f800000
QNAN = 0x7fc00000


def decode(bits):
    magnitude = bits & MASK
    exponent = magnitude >> 23
    sig = (magnitude & 0x7fffff) | (int(exponent != 0) << 23)
    return sig, max(exponent, 1) - 150


def units(bits):
    sig, exponent = decode(bits)
    value = sig << (exponent + 149)
    return -value if bits >> 31 else value


def special(a, b, c):
    ma, mb, mc = a & MASK, b & MASK, c & MASK
    psign = (a ^ b) & 0x80000000
    if max(ma, mb, mc) > INF or (ma == 0 and mb == INF) or (ma == INF and mb == 0):
        return QNAN
    if ma == INF or mb == INF:
        if mc == INF and (psign ^ c) >> 31:
            return QNAN
        return psign | INF
    if mc == INF:
        return c
    return None


def exact(a, b, c, nearest):
    result = special(a, b, c)
    if result is not None:
        return result
    n = units(a) * units(b) + (units(c) << 149)
    if n == 0:
        return ((a ^ b) & c) & 0x80000000
    sign = int(n < 0) << 31
    n = abs(n)
    quantum = max(n.bit_length() - 1 - 298 - 23, -149)
    shift = quantum + 298
    q, r = divmod(n, 1 << shift)
    half = 1 << (shift - 1)
    if nearest:
        q += int(r > half or (r == half and q & 1))
    if q >= 1 << 24:
        q >>= 1
        quantum += 1
    if q < 1 << 23:
        return sign | q
    exponent = quantum + 150
    return sign | (INF if nearest else INF - 1) if exponent >= 255 else sign | (exponent << 23) | (q & 0x7fffff)



rng = random.Random(0xF0AF32)
edges = [0, 1, 0x7fffff, 0x800000, 0x3f800000, INF, QNAN]
edges += [bits | 0x80000000 for bits in edges]
triples = [(a, b, c) for a in edges for b in edges for c in edges]
triples.extend([
    (0x3f800001, 0x3f7ffffe, 0xbf800000),
    (0x7f7fffff, 0x40000000, 0xff7fffff),
    (1, 0x3f000000, 1),
    (0x80000001, 0x3f000000, 0),
    (INF, 0, INF), (0, INF, 0xff800000),
])
for exponent in range(1, 255):
    first = (exponent << 23) | rng.getrandbits(23)
    triples.append((first, 0x3f800001, first ^ 0x80000000))
# Neighbor cancellation when product and addend leading exponents match or differ by one.
for _ in range(100):
    first = (rng.randrange(70, 180) << 23) | rng.getrandbits(23)
    second = 0x3f000000 | rng.getrandbits(23)
    product = exact(first, second, 0, True)
    for delta in [-1, 0, 1]:
        triples.append((first, second, (product + delta) ^ 0x80000000))
# Alignment boundaries, including distances exceeding the pair width.
for gap in [0, 1, 2, 3, 4, 31, 32, 63, 64, 126, 127, 149, 150, 200, 276, 403]:
    product_exponent = 0 if gap <= 149 else (127 if gap <= 276 else 254)
    c_exponent = product_exponent - gap
    c = (c_exponent + 127) << 23 if c_exponent >= -126 else 1 << (c_exponent + 149)
    a = 0x3f800000 if product_exponent == 0 else 0x7f000000
    b = 0x7f000000 if product_exponent == 254 else 0x3f800000
    for sign in [0, 0x80000000]:
        triples.append((a, b, c | sign))
# Tiny signed perturbations resolve exact product halfway cases in both directions.
for first in [0x3f800001, 0x3f800003]:
    for gap in [3, 4, 24, 25, 31, 32, 63, 64, 127, 149]:
        c = (127 - gap) << 23 if gap <= 126 else 1 << (149 - gap)
        for sign in [0, 0x80000000]:
            triples.append((first, 0x3fc00000, c | sign))
for first in [0x7f000001, 0x7f000003]:
    for gap in [31, 32, 63, 64, 127, 149, 200, 276]:
        exponent = 127 - gap
        c = (exponent + 127) << 23 if exponent >= -126 else 1 << (exponent + 149)
        for sign in [0, 0x80000000]:
            triples.append((first, 0x3fc00000, c | sign))
# Product exactly at the maxfinite/infinity midpoint; tiny c selects its side.
assert (31 * 601 * 1801) == (1 << 25) - 1
assert (31 * 601) << 9 == 0x918e00
assert 1801 << 13 == 0xe12000
for product_sign in [0, 0x80000000]:
    for addend in [0, 0x80000000, 1, 0x80000001]:
        triples.append((0x7f118e00 | product_sign, 0x3fe12000, addend))
# Exact lattice products with opposite tiny addends must lose one ULP in RZ.
for first in [0x3f800000, 0x3f800001, 0x40000000, 0x7f000000]:
    for second in [0x3f800000, 0x40000000]:
        for product_sign in [0, 0x80000000]:
            for addend in [1, 0x80000001, 0x00800000, 0x80800000]:
                triples.append((first | product_sign, second, addend))
triples.extend([(3, 0x3f000000, 1), (0x80000003, 0x3f000000, 0x80000001)])
while len(triples) < 4096:
    triples.append((rng.getrandbits(32), rng.getrandbits(32), rng.getrandbits(32)))
assert len(triples) == 4096
with Path(__file__).with_name("fmaf-rz-values.csv").open("w") as output:
    output.write(
        "# Generated by fmaf_rz_reference.py; seed 0xF0AF32; "
        "exact bigint a*b+c units 2^-298 RZ and RN-even, canonical NaN 7fc00000\n"
    )
    for first, second, third in triples:
        output.write(f"{first:08x},{second:08x},{third:08x},{exact(first, second, third, False):08x},{exact(first, second, third, True):08x}\n")
