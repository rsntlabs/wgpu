#!/usr/bin/env python3
"""Regenerate binary32 division RZ/RN references by exact rational rounding."""
from pathlib import Path
import random

MASK = 0x7fffffff
INF = 0x7f800000
QNAN = 0x7fc00000


def exact(a, b, nearest):
    ma, mb = a & MASK, b & MASK
    sign = (a ^ b) & 0x80000000
    if ma > INF or mb > INF or (ma == 0 and mb == 0) or (ma == INF and mb == INF):
        return QNAN
    if ma == INF or mb == 0:
        return sign | INF
    if ma == 0 or mb == INF:
        return sign
    ea, eb = ma >> 23, mb >> 23
    numerator = (ma & 0x7fffff) | (int(ea != 0) << 23)
    denominator = (mb & 0x7fffff) | (int(eb != 0) << 23)
    scale = max(ea, 1) - max(eb, 1)
    leading = numerator.bit_length() - denominator.bit_length()
    below = numerator < (denominator << leading) if leading >= 0 else (numerator << -leading) < denominator
    leading -= int(below)
    quantum = max(leading + scale - 23, -149)
    shift = scale - quantum
    if shift >= 0:
        numerator <<= shift
    else:
        denominator <<= -shift
    quotient, remainder = divmod(numerator, denominator)
    if nearest:
        quotient += int(2 * remainder > denominator or (2 * remainder == denominator and quotient & 1))
    if quotient == 0:
        return sign
    if quotient >= 1 << 24:
        quotient >>= 1
        quantum += 1
    if quotient < 1 << 23:
        return sign | quotient
    exponent = quantum + 150
    if exponent >= 255:
        return sign | (INF if nearest else INF - 1)
    return sign | (exponent << 23) | (quotient & 0x7fffff)


rng = random.Random(0xFD1032)
edges = [
    0, 1, 2, 3, 5, 0x400000, 0x7fffff, 0x800000, 0x800001,
    0xffffff, 0x3f000000, 0x3f7fffff, 0x3f800000, 0x3f800001,
    0x40000000, 0x40400000, 0x7f000000, 0x7f7fffff, INF, INF + 1, QNAN, 0x7fffffff,
]
edges += [value | 0x80000000 for value in edges]
pairs = [(first, second) for first in edges for second in edges]
for exponent in range(1, 255):
    first = (exponent << 23) | rng.getrandbits(23)
    pairs.append((first, 0x3f800001))
    pairs.append((first, 0x3f7fffff))
    pairs.append((first, (rng.randrange(1, 255) << 23) | rng.getrandbits(23)))
for first, second in [(0xc1efffff, 0x41400000), (0x7f7fffff, 0x3f7fffff),
                      (0x7f7fffff, 0x3f800001), (0x800000, 0x3f800001),
                      (0xffffff, 0x40000000), (0x800001, 0x40000000)]:
    for sign_a in [0, 0x80000000]:
        for sign_b in [0, 0x80000000]:
            pairs.append((first ^ sign_a, second ^ sign_b))
while len(pairs) < 4096:
    pairs.append((rng.getrandbits(32), rng.getrandbits(32)))
assert len(pairs) == 4096
with Path(__file__).with_name("fdiv-rz-values.csv").open("w") as output:
    output.write(
        "# Generated by fdiv_rz_reference.py; seed 0xFD1032; "
        "exact rational quotient/remainder RZ and RN-even, canonical NaN 7fc00000\n"
    )
    for first, second in pairs:
        output.write(f"{first:08x},{second:08x},{exact(first, second, False):08x},{exact(first, second, True):08x}\n")
