#!/usr/bin/env python3
"""Regenerate binary32 sum references in RZ and RN using exact integer units."""
from pathlib import Path
import random

MASK = 0x7fffffff
INF = 0x7f800000
QNAN = 0x7fc00000


def exact(a, b, nearest):
    ma, mb = a & MASK, b & MASK
    if ma > INF or mb > INF:
        return QNAN
    if ma == INF or mb == INF:
        if ma == mb and (a ^ b) >> 31:
            return QNAN
        return a if ma == INF else b
    def units(bits):
        magnitude = bits & MASK
        exponent = magnitude >> 23
        sig = (magnitude & 0x7fffff) | (int(exponent != 0) << 23)
        value = sig << (max(exponent, 1) - 1)
        return -value if bits >> 31 else value
    total = units(a) + units(b)
    if total == 0:
        return a & b & 0x80000000
    sign = int(total < 0) << 31
    magnitude = abs(total)
    if magnitude < 1 << 23:
        return sign | magnitude
    shift = max(0, magnitude.bit_length() - 24)
    quotient, remainder = divmod(magnitude, 1 << shift)
    if nearest and shift:
        half = 1 << (shift - 1)
        quotient += int(remainder > half or (remainder == half and quotient & 1))
    if quotient >= 1 << 24:
        quotient >>= 1
        shift += 1
    exponent = shift + 1
    if exponent >= 255:
        return sign | (INF if nearest else INF - 1)
    return sign | (exponent << 23) | (quotient & 0x7fffff)


rng = random.Random(0xFA0032)
edges = [0, 1, 2, 3, 0x3fffff, 0x400000, 0x7fffff, 0x800000, 0x800001,
         0x3f000000, 0x3f7fffff, 0x3f800000, 0x3f800001, 0x40000000,
         0x7f7ffffe, 0x7f7fffff, INF, INF + 1, QNAN, 0x7fffffff]
edges += [bits | 0x80000000 for bits in edges]
pairs = [(first, second) for first in edges for second in edges]
for exponent in range(1, 255):
    first = (exponent << 23) | rng.getrandbits(23)
    pairs.append((first, first ^ 0x80000000))
    pairs.append((first, (first + 1) ^ 0x80000000))
    if exponent >= 24:
        half = ((exponent - 24) << 23) if exponent >= 25 else 0x400000
        for delta in [-1, 0, 1]:
            pairs.append((first, max(0, half + delta)))
            pairs.append((first | 0x80000000, max(0, half + delta) | 0x80000000))
for gap in [1, 23, 24, 25, 31, 32, 63, 64, 126, 127, 149]:
    small = ((127 - gap) << 23) if gap <= 126 else 1 << (149 - gap)
    for sign_a in [0, 0x80000000]:
        for sign_b in [0, 0x80000000]:
            pairs.append((0x3f800000 | sign_a, small | sign_b))
while len(pairs) < 4096:
    pairs.append((rng.getrandbits(32), rng.getrandbits(32)))
assert len(pairs) == 4096
with Path(__file__).with_name("fadd-rz-values.csv").open("w") as output:
    output.write(
        "# Generated by fadd_rz_reference.py; seed 0xFA0032; "
        "exact sum units 2^-149, RZ and RN-even, canonical NaN 7fc00000\n"
    )
    for first, second in pairs:
        output.write(f"{first:08x},{second:08x},{exact(first, second, False):08x},{exact(first, second, True):08x}\n")
