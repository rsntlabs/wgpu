#!/usr/bin/env python3
"""Regenerate reciprocal-root references by exact bigint midpoint comparisons."""
from pathlib import Path
import random

INF = 0x7f800000
QNAN = 0x7fc00000


def units(bits):
    exponent = bits >> 23
    significand = (bits & 0x7fffff) | (int(exponent != 0) << 23)
    return significand << (max(exponent, 1) - 1)


def exact(bits):
    magnitude = bits & 0x7fffffff
    if magnitude == 0:
        return (bits & 0x80000000) | INF
    if bits >> 31 or magnitude > INF:
        return QNAN
    if bits == INF:
        return 0
    x = units(bits)
    target = 1 << 447
    low, high = 0, INF - 1
    while low + 1 < high:
        middle = (low + high) // 2
        if x * units(middle) ** 2 <= target:
            low = middle
        else:
            high = middle
    comparison = x * (units(low) + units(high)) ** 2
    if comparison < 4 * target or (comparison == 4 * target and low & 1):
        return high
    return low


rng = random.Random(0xF25236)
inputs = [0, 1, 2, 3, 0x3fffff, 0x400000, 0x7fffff, 0x800000, 0x800001,
          0xffffff, 0x733698, 0x33ff3, 0x3f7fffff, 0x3f800000, 0x3f800001,
          0x40000000, 0x40800000, 0x41100000, 0x7f7fffff, INF, INF + 1,
          0x7fbfffff, QNAN, 0x7fc12345, 0x7fffffff]
inputs += [bits | 0x80000000 for bits in inputs]
for exponent in range(1, 255):
    for mantissa in [0, 1, 0x7fffff, rng.getrandbits(23)]:
        bits = (exponent << 23) | mantissa
        inputs.extend([bits, bits | 0x80000000])
# Locate representable x values on both sides of reciprocal-root midpoints.
for _ in range(256):
    output = rng.randrange(0x1f800000, 0x64800000)
    midpoint_squared = (units(output) + units(output + 1)) ** 2
    low, high = 0, INF - 1
    while low + 1 < high:
        middle = (low + high) // 2
        if units(middle) * midpoint_squared <= 1 << 449:
            low = middle
        else:
            high = middle
    for bits in [low, high]:
        inputs.extend([bits, bits | 0x80000000])
while len(inputs) < 4096:
    inputs.append(rng.getrandbits(32))
assert len(inputs) == 4096
assert exact(0x800001) == 0x5effffff
assert exact(0xffffff) == 0x5eb504f4
with Path(__file__).with_name("frsqrt-rn-values.csv").open("w") as output:
    output.write(
        "# Generated by frsqrt_rn_reference.py; seed 0xF25236; "
        "exact bigint x*midpoint^2 RN-even, canonical NaN 7fc00000\n"
    )
    for bits in inputs:
        output.write(f"{bits:08x},{exact(bits):08x}\n")
