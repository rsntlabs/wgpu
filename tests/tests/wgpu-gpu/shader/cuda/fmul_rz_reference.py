#!/usr/bin/env python3
"""Regenerate binary32 multiplication RZ/RN references using exact bigint products."""
from pathlib import Path
import random

MASK = 0x7fffffff
INF = 0x7f800000
QNAN = 0x7fc00000


def exact(a, b, nearest):
    ma, mb = a & MASK, b & MASK
    sign = (a ^ b) & 0x80000000
    if ma > INF or mb > INF:
        return QNAN
    if ma == INF or mb == INF:
        return QNAN if ma == 0 or mb == 0 else sign | INF
    if ma == 0 or mb == 0:
        return sign
    ea, eb = ma >> 23, mb >> 23
    sa = (ma & 0x7fffff) | (int(ea != 0) << 23)
    sb = (mb & 0x7fffff) | (int(eb != 0) << 23)
    n = sa * sb
    scale = max(ea, 1) + max(eb, 1) - 300
    leading = n.bit_length() - 1
    # Keep 24 significant bits except at fixed subnormal quantum 2^-149.
    quantum = max(leading + scale - 23, -149)
    shift = quantum - scale
    if shift > 0:
        q, r = divmod(n, 1 << shift)
        half = 1 << (shift - 1)
        if nearest:
            q += int(r > half or (r == half and q & 1))
    else:
        q = n << -shift
    if q == 0:
        return sign
    if q >= 1 << 24:
        q >>= 1
        quantum += 1
    if q < 1 << 23:
        return sign | q
    exponent = quantum + 150
    if exponent >= 255:
        return sign | (INF if nearest else INF - 1)
    return sign | (exponent << 23) | (q & 0x7fffff)


rng = random.Random(0xF0001)
edges = [0, 1, 2, 3, 0x3fffff, 0x400000, 0x400001, 0x7fffff,
         0x800000, 0x800001, 0x3f000000, 0x3f7fffff, 0x3f800000,
         0x3f800001, 0x3f7ffffe, 0x3ffffffe, 0x7f000001, 0x3fffffff, 0x40000000, 0x7f000000, 0x7f7fffff,
         INF, INF + 1, QNAN, 0x7fffffff]
edges += [value | 0x80000000 for value in edges]
pairs = [(first, second) for first in edges for second in edges]
for exponent in range(1, 255):
    first = (exponent << 23) | rng.getrandbits(23)
    pairs.append((first, 0x3f800001))
    other_exponent = max(0, min(254, 126 - exponent))
    pairs.append((first, (other_exponent << 23) | rng.getrandbits(23)))
    pairs.append((first | 0x80000000, 0x7f000000))
# Exact halfway cases with known low product bits, all sign combinations.
for significand in [0x800001, 0x800003, 0xffffff]:
    for sign_a in [0, 0x80000000]:
        for sign_b in [0, 0x80000000]:
            pairs.append((
                (0x3f000000 | (significand & 0x7fffff)) | sign_a,
                0x3fc00000 | sign_b,
            ))
while len(pairs) < 4096:
    pairs.append((rng.getrandbits(32), rng.getrandbits(32)))
assert len(pairs) == 4096
with Path(__file__).with_name("fmul-rz-values.csv").open("w") as output:
    output.write(
        "# Generated by fmul_rz_reference.py; seed 0xF0001; "
        "exact bigint products, RZ and RN-even, canonical NaN 7fc00000\n"
    )
    for first, second in pairs:
        output.write(f"{first:08x},{second:08x},{exact(first, second, False):08x},{exact(first, second, True):08x}\n")
