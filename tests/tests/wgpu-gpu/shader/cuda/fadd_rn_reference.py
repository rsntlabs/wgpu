#!/usr/bin/env python3
"""Regenerate fadd-rn-values.csv using exact integer binary32 addition."""
from pathlib import Path
import random

MASK = 0x7fffffff
INF = 0x7f800000
QNAN = 0x7fc00000


def exact(a, b):
    """Exact integer-units oracle, independently rounded with arbitrary precision."""
    ma, mb = a & MASK, b & MASK
    if ma > INF or mb > INF:
        return QNAN
    if ma == INF or mb == INF:
        if ma == mb and (a ^ b) >> 31:
            return QNAN
        return a if ma == INF else b
    def units(word):
        magnitude = word & MASK
        exponent = magnitude >> 23
        significand = (magnitude & 0x7fffff) | (int(exponent != 0) << 23)
        value = significand << (max(exponent, 1) - 1)
        return -value if word >> 31 else value
    total = units(a) + units(b)
    if total == 0:
        return (a & b) & 0x80000000
    sign = int(total < 0) << 31
    n = abs(total)
    if n.bit_length() <= 23:
        return sign | n
    shift = max(0, n.bit_length() - 24)
    sig = n >> shift
    if shift:
        remainder = n - (sig << shift)
        halfway = 1 << (shift - 1)
        sig += int(remainder > halfway or (remainder == halfway and sig & 1))
    if sig >= 1 << 24:
        sig >>= 1
        shift += 1
    exponent = shift + 1
    if exponent >= 255:
        return sign | INF
    return sign | (exponent << 23) | (sig & 0x7fffff)


rng = random.Random(0xFADD32)
pairs = []
edges = [
    0, 1, 0x7fffff, 0x800000, 0x3f000000, 0x3f7fffff,
    0x3f800000, 0x3f800001, 0x7f7fffff, INF, INF + 1, 0x7fc12345,
]
edges += [word | 0x80000000 for word in edges]
for a in edges:
    for b in edges:
        pairs.append((a, b))
for exponent in range(1, 255):
    a = (exponent << 23) | rng.getrandbits(23)
    pairs.append((a, a ^ 0x80000000))
    pairs.append((a, ((a + 1) & MASK) ^ 0x80000000))
    if exponent >= 24:
        half = ((exponent - 24) << 23) if exponent >= 25 else 0x400000
        for delta in [-1, 0, 1]:
            pairs.append((a, max(0, half + delta)))
            pairs.append((a, 0x80000000 | max(0, half + delta)))
while len(pairs) < 4096:
    pairs.append((rng.getrandbits(32), rng.getrandbits(32)))
assert len(pairs) == 4096
with Path(__file__).with_name("fadd-rn-values.csv").open("w") as output:
    output.write(
        "# Generated by fadd_rn_reference.py; seed 0xFADD32; "
        "exact integer units 2^-149, RN-even, canonical NaN 7fc00000\n"
    )
    for a, b in pairs:
        output.write(f"{a:08x},{b:08x},{exact(a,b):08x}\n")
