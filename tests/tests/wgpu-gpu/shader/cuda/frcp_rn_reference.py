#!/usr/bin/env python3
"""Regenerate binary32 reciprocal references by exact rational RN-even rounding."""
from pathlib import Path
import random


def exact(bits):
    magnitude = bits & 0x7fffffff
    sign = bits & 0x80000000
    if magnitude > 0x7f800000:
        return 0x7fc00000
    if magnitude == 0:
        return sign | 0x7f800000
    if magnitude == 0x7f800000:
        return sign
    exponent = magnitude >> 23
    denominator = (magnitude & 0x7fffff) | (int(exponent != 0) << 23)
    scale = 150 - max(exponent, 1)
    numerator = 1
    leading = -denominator.bit_length()
    if denominator & (denominator - 1) == 0:
        leading += 1
    quantum = max(leading + scale - 23, -149)
    shift = scale - quantum
    if shift >= 0:
        numerator <<= shift
    else:
        denominator <<= -shift
    quotient, remainder = divmod(numerator, denominator)
    quotient += int(2 * remainder > denominator or (2 * remainder == denominator and quotient & 1))
    if quotient >= 1 << 24:
        quotient >>= 1
        quantum += 1
    if quotient < 1 << 23:
        return sign | quotient
    biased = quantum + 150
    if biased >= 255:
        return sign | 0x7f800000
    return sign | (biased << 23) | (quotient & 0x7fffff)


rng = random.Random(0xF2C032)
inputs = [0, 1, 2, 3, 0x1fffff, 0x200000, 0x200001, 0x200002,
          0x7fffff, 0x800000, 0x800001, 0x3f7fffff, 0x3f800000, 0x3f800001,
          0x7f7ffffe, 0x7f7fffff, 0x7f800000, 0x7f800001, 0x7fbfffff,
          0x7fc00000, 0x7fc12345, 0x7fffffff]
inputs += [bits | 0x80000000 for bits in inputs]
for exponent in range(1, 255):
    for mantissa in [0, 1, 0x7fffff, rng.getrandbits(23)]:
        bits = (exponent << 23) | mantissa
        inputs.extend([bits, bits | 0x80000000])
while len(inputs) < 4096:
    inputs.append(rng.getrandbits(32))
assert len(inputs) == 4096
with Path(__file__).with_name("frcp-rn-values.csv").open("w") as output:
    output.write(
        "# Generated by frcp_rn_reference.py; seed 0xF2C032; "
        "exact rational 1/x quotient/remainder RN-even, canonical NaN 7fc00000\n"
    )
    for bits in inputs:
        output.write(f"{bits:08x},{exact(bits):08x}\n")
