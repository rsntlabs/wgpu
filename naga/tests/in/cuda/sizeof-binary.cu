__global__ void sizeof_binary(const int *input, unsigned *output) {
    unsigned lane = threadIdx.x;
    unsigned base = 4u + lane * 24u;
    int seed = input[lane];
    unsigned other = 33u;
    float real = 2.0f;
    int counter = 7;
    int &watched = seed;
    int grid[2][3]{};
    constexpr unsigned Add = unsigned(sizeof(seed + other));
    constexpr unsigned Subtract = unsigned(sizeof(seed - other));
    constexpr unsigned Multiply = unsigned(sizeof(seed * real));
    constexpr unsigned Divide = unsigned(sizeof(1 / 0));
    constexpr unsigned Modulo = unsigned(sizeof(seed % other));
    constexpr unsigned Left = unsigned(sizeof(seed << other));
    constexpr unsigned Right = unsigned(sizeof(seed >> other));
    constexpr unsigned And = unsigned(sizeof(seed & other));
    constexpr unsigned Or = unsigned(sizeof(seed | other));
    constexpr unsigned Xor = unsigned(sizeof(seed ^ other));
    constexpr unsigned Less = unsigned(sizeof(seed < other));
    constexpr unsigned Equal = unsigned(sizeof(seed == other));
    constexpr unsigned LogicalAnd = unsigned(sizeof(seed && other));
    constexpr unsigned LogicalOr = unsigned(sizeof(seed || other));
    constexpr unsigned Nested = unsigned(sizeof((seed + other) * real));
    constexpr unsigned Row = unsigned(sizeof(grid[seed + other]));
    constexpr unsigned Element = unsigned(sizeof(grid[seed - other][seed * other]));
    constexpr unsigned Reference = unsigned(sizeof(watched + seed));
    constexpr unsigned BinaryIndex = unsigned(sizeof(grid[(seed << other) & 1]));
    constexpr unsigned InvalidShift = unsigned(sizeof(1 << 32));
    constexpr unsigned ReferenceDivide = unsigned(sizeof(watched / 0));
    constexpr unsigned GroupedComparison = unsigned(sizeof((seed + other) != counter));
    output[base] = Add; output[base + 1u] = Subtract; output[base + 2u] = Multiply;
    output[base + 3u] = Divide; output[base + 4u] = Modulo; output[base + 5u] = Left;
    output[base + 6u] = Right; output[base + 7u] = And; output[base + 8u] = Or;
    output[base + 9u] = Xor; output[base + 10u] = Less; output[base + 11u] = Equal;
    output[base + 12u] = LogicalAnd; output[base + 13u] = LogicalOr;
    output[base + 14u] = Nested; output[base + 15u] = Row;
    output[base + 16u] = Element; output[base + 17u] = Reference;
    output[base + 18u] = BinaryIndex; output[base + 19u] = InvalidShift;
    output[base + 20u] = unsigned(counter); output[base + 21u] = unsigned(seed);
    output[base + 22u] = ReferenceDivide; output[base + 23u] = GroupedComparison;
}
