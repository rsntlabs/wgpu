    output[base + 11u] = unsigned(fresh_triples[1].z);
    constexpr unsigned TripleBytes = unsigned(sizeof(fresh_triples));
    output[base + 12u] = TripleBytes;
    Record records[2]{};
    decltype(records) fresh_records{};
    fresh_records[1] = Record{4, 5};
    output[base + 13u] = unsigned(fresh_records[1].x + fresh_records[1].y);
    constexpr unsigned RecordBytes = unsigned(sizeof(fresh_records));
    output[base + 14u] = RecordBytes;
    const int constants[2] = {3, 4};
    decltype(constants) fresh_constants{5, 6};
    output[base + 15u] = unsigned(fresh_constants[1]);
}
