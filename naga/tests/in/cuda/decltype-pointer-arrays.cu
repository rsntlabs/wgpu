using Row = int[3];
struct Record { int x; int y; };
__device__ unsigned adjusted_shape(Row grid[2]) {
    using Pointer = decltype(grid);
    Pointer copy = grid;
    constexpr unsigned Shape = unsigned(sizeof(Pointer) + sizeof(*copy));
    return Shape;
}
__global__ void decltype_pointer_arrays(const int *input, unsigned *output) {
    unsigned lane = threadIdx.x;
    unsigned base = 4u + lane * 16u;
    int local = input[lane];
    int *pointer = &local;
    decltype(pointer) copy = pointer;
    *copy += 2;
    int *const fixed = &local;
    decltype(fixed) fixed_copy = &local;
    *fixed_copy += 3;
    output[base] = unsigned(local);
    decltype(input) readonly = input + lane;
    readonly = input + lane + 1u;
    output[base + 1u] = unsigned(*readonly);
    int cursor = 0;
    int values[2] = {input[lane], 10};
    int *selected = &values[cursor++];
    decltype(selected) alias = selected;
    *alias += 7;
    output[base + 2u] = unsigned(cursor);
    output[base + 3u] = unsigned(values[0]);
    Row row{1, 2, 3};
    decltype(row) fresh_row{4, 5, 6};
    output[base + 4u] = unsigned(fresh_row[1]);
    constexpr unsigned RowBytes = unsigned(sizeof(fresh_row));
    output[base + 5u] = RowBytes;
    int grid[2][3]{};
    decltype(grid) fresh_grid{};
    fresh_grid[1][2] = local;
    output[base + 6u] = unsigned(fresh_grid[1][2]);
    output[base + 7u] = adjusted_shape(grid);
    constexpr unsigned GridBytes = unsigned(sizeof(fresh_grid));
    output[base + 8u] = GridBytes;
    int1 ones[2]{};
    decltype(ones) fresh_ones{};
    fresh_ones[1] = int1{9};
    output[base + 9u] = unsigned(fresh_ones[1].x);
    constexpr unsigned OneBytes = unsigned(sizeof(fresh_ones));
    output[base + 10u] = OneBytes;
    float3 triples[2]{};
    decltype(triples) fresh_triples{};
