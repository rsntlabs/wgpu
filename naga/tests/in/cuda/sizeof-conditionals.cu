__global__ void sizeof_conditionals(const int *input, unsigned *output) {
    unsigned lane = threadIdx.x;
    unsigned base = 4u + lane * 20u;
    int seed = input[lane];
    bool flag = seed != 0;
    int small;
    int other;
    bool unknown;
    int cursor = 7;
    int &watched = cursor;
    int grid[2][3]{};
    constexpr unsigned SameType = unsigned(sizeof(flag ? small : other));
    constexpr unsigned Boolean = unsigned(sizeof(flag ? true : unknown));
    constexpr unsigned Promoted = unsigned(sizeof(flag ? small : seed));
    constexpr unsigned BoolInt = unsigned(sizeof(flag ? unknown : small));
    constexpr unsigned Real = unsigned(sizeof(flag ? seed : 1.0f));
    constexpr unsigned NestedMiddle = unsigned(sizeof(flag ? unknown ? small : other : small));
    constexpr unsigned NestedFinal = unsigned(sizeof(flag ? small : unknown ? other : small));
    constexpr unsigned Grouped = unsigned(sizeof(flag ? (unknown ? small : other) : small));
    constexpr unsigned Logical = unsigned(sizeof(flag || unknown ? small : other));
    constexpr unsigned Row = unsigned(sizeof(grid[flag ? cursor : seed]));
    constexpr unsigned Element = unsigned(sizeof(grid[flag ? cursor : seed][unknown ? 0 : 1]));
    constexpr unsigned InvalidDivide = unsigned(sizeof(1 / 0 ? small : other));
    constexpr unsigned InvalidShift = unsigned(sizeof(flag ? 1 << -1 : seed));
    constexpr unsigned Reference = unsigned(sizeof(flag ? watched : seed));
    constexpr unsigned Storage = unsigned(sizeof(flag ? input[cursor] : input[seed]));
    constexpr unsigned UnaryBinding = sizeof unknown ? 7u : 9u;
    constexpr unsigned AddBinding = unsigned(sizeof small + 1);
    output[base] = SameType; output[base + 1u] = Boolean;
    output[base + 2u] = Promoted; output[base + 3u] = BoolInt;
    output[base + 4u] = Real; output[base + 5u] = NestedMiddle;
    output[base + 6u] = NestedFinal; output[base + 7u] = Grouped;
    output[base + 8u] = Logical; output[base + 9u] = Row;
    output[base + 10u] = Element; output[base + 11u] = InvalidDivide;
    output[base + 12u] = InvalidShift; output[base + 13u] = Reference;
    output[base + 14u] = Storage; output[base + 15u] = UnaryBinding;
    output[base + 16u] = AddBinding; output[base + 17u] = unsigned(cursor);
    output[base + 18u] = unsigned(seed); output[base + 19u] = unsigned(flag);
}
